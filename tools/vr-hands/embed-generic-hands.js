#!/usr/bin/env node
/**
 * Embeds the vendored WebXR generic-hand GLBs into a TypeScript module so the
 * runtime never has to resolve an asset URL. See README.md in this folder.
 */
const fs = require('fs');
const path = require('path');

const sourceDirectory = path.join(__dirname, 'generic-hand');
const outputFile = path.join(__dirname, '..', '..', 'src', 'vr', 'runtime', 'hands', 'GenericHandGLB.generated.ts');

function readGlb(hand) {
  const file = path.join(sourceDirectory, `${hand}.glb`);
  const bytes = fs.readFileSync(file);
  if (bytes.readUInt32LE(0) !== 0x46546c67) {
    throw new Error(`${file} is not a binary glTF (missing glTF magic)`);
  }
  return bytes.toString('base64');
}

const left = readGlb('left');
const right = readGlb('right');
const eol = '\r\n';
const lines = [
  '// GENERATED by tools/vr-hands/embed-generic-hands.js — do not edit by hand.',
  '//',
  '// WebXR generic-hand models from @webxr-input-profiles/assets 1.0.20.',
  '// MIT License, Copyright (c) 2019 Amazon. Full notice:',
  '// tools/vr-hands/generic-hand/LICENSE.md',
  '',
  `export const GENERIC_HAND_LEFT_GLB_BASE64 = '${left}';`,
  '',
  `export const GENERIC_HAND_RIGHT_GLB_BASE64 = '${right}';`,
  '',
];
fs.writeFileSync(outputFile, lines.join(eol));
console.log(`wrote ${path.relative(process.cwd(), outputFile)} (${left.length + right.length} base64 chars)`);
